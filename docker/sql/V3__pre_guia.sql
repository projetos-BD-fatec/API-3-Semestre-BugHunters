CREATE TABLE CATALOGO_TUSS (
    COD_TUSS        VARCHAR2(200 CHAR) CONSTRAINT PK_CATALOGO_TUSS PRIMARY KEY,
    DESC_TUSS       VARCHAR2(250 CHAR) NOT NULL,
    TABELA_TUSS     VARCHAR2(50 CHAR),
    INICIO_VIGENCIA DATE,
    FIM_VIGENCIA    DATE
);

CREATE TABLE EXAME (
    ID_EXAME   NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT PK_EXAME_ID PRIMARY KEY,
    COD_TUSS   VARCHAR2(200 CHAR) NOT NULL
                 CONSTRAINT FK_EXAME_COD_TUSS REFERENCES CATALOGO_TUSS (COD_TUSS),
    DESC_EXAME VARCHAR2(250 CHAR) NOT NULL,
    CONSTRAINT UK_EXAME_COD_TUSS UNIQUE (COD_TUSS)
);

CREATE TABLE EXAME_PRESTADOR (
    ID_EXAME_PRESTADOR NUMBER GENERATED BY DEFAULT AS IDENTITY
                         CONSTRAINT PK_EXAME_PRESTADOR_ID PRIMARY KEY,
    ID_EXAME           NUMBER
                         CONSTRAINT FK_EXAME_PRESTADOR_EXAME REFERENCES EXAME (ID_EXAME),
    ID_PRESTADOR       NUMBER
                         CONSTRAINT FK_EXAME_PRESTADOR_PRESTADOR REFERENCES PRESTADOR (ID_PRESTADOR),
    VALOR_CONTRATUAL   NUMBER(14,2) NOT NULL,
    STATUS             VARCHAR2(10 CHAR) DEFAULT 'ATIVO' NOT NULL,
    DT_INICIO_VIGENCIA DATE NOT NULL,
    DT_FIM_VIGENCIA    DATE
);

CREATE TABLE PRE_GUIA (
    ID_PRE_GUIA  NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT PK_PRE_GUIA PRIMARY KEY,
    ID_USUARIO   NUMBER
                   CONSTRAINT FK_PRE_GUIA_USUARIO REFERENCES USUARIO (ID_USUARIO),
    NM_ANEXO     VARCHAR2(250 CHAR),
    STATUS       VARCHAR2(20 CHAR) DEFAULT 'EM_ANALISE',
    CRIADO_EM    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

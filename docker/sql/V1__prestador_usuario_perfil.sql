CREATE TABLE PRESTADOR (
  ID_PRESTADOR     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NM_PRESTADOR     VARCHAR2(200 CHAR) NOT NULL,
  NM_FANTASIA      VARCHAR2(200 CHAR),
  TP_PRESTADOR     VARCHAR2(10 CHAR)  NOT NULL,
  TP_DOCUMENTO     VARCHAR2(4 CHAR)   NOT NULL,
  NR_DOCUMENTO     VARCHAR2(14 CHAR),
  DS_LOGRADOURO    VARCHAR2(200 CHAR),
  NR_ENDERECO      VARCHAR2(20 CHAR),
  DS_COMPLEMENTO   VARCHAR2(100 CHAR),
  NM_BAIRRO        VARCHAR2(100 CHAR),
  NM_CIDADE        VARCHAR2(100 CHAR),
  SG_UF            CHAR(2),
  NR_CEP           VARCHAR2(8 CHAR),
  FL_ATIVO         CHAR(1) DEFAULT 'S' NOT NULL,
  CRIADO_EM        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM    TIMESTAMP(6),
  CONSTRAINT PK_PRESTADOR PRIMARY KEY (ID_PRESTADOR),
  CONSTRAINT UK_PRESTADOR_DOC UNIQUE (NR_DOCUMENTO),
  CONSTRAINT CK_PRESTADOR_TIPO  CHECK (TP_PRESTADOR IN ('OCS','PSA')),
  CONSTRAINT CK_PRESTADOR_ATIVO CHECK (FL_ATIVO IN ('S','N')),
  CONSTRAINT CK_PRESTADOR_TPDOC CHECK (
        (TP_PRESTADOR = 'OCS' AND TP_DOCUMENTO = 'CNPJ')
     OR (TP_PRESTADOR = 'PSA' AND TP_DOCUMENTO = 'CPF')),
  CONSTRAINT CK_PRESTADOR_NRDOC CHECK (
        NR_DOCUMENTO IS NULL
     OR (TP_DOCUMENTO = 'CNPJ' AND REGEXP_LIKE(NR_DOCUMENTO,'^[0-9]{14}$'))
     OR (TP_DOCUMENTO = 'CPF'  AND REGEXP_LIKE(NR_DOCUMENTO,'^[0-9]{11}$')))
);

CREATE TABLE USUARIO (
  ID_USUARIO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_PRESTADOR     NUMBER,
  ID_UG            NUMBER,
  NM_USUARIO       VARCHAR2(150 CHAR) NOT NULL,
  DS_EMAIL         VARCHAR2(150 CHAR) NOT NULL,
  DS_SENHA_HASH    VARCHAR2(200 CHAR) NOT NULL,
  NR_CPF           VARCHAR2(11 CHAR),
  NR_TELEFONE      VARCHAR2(20 CHAR),
  FL_ATIVO         CHAR(1) DEFAULT 'S' NOT NULL,
  DT_ULTIMO_ACESSO TIMESTAMP(6),
  CRIADO_EM        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM    TIMESTAMP(6),
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_USUARIO_PREST FOREIGN KEY (ID_PRESTADOR) REFERENCES PRESTADOR (ID_PRESTADOR),
  CONSTRAINT CK_USUARIO_ATIVO CHECK (FL_ATIVO IN ('S','N')),
  CONSTRAINT CK_USUARIO_CPF   CHECK (NR_CPF IS NULL OR REGEXP_LIKE(NR_CPF,'^[0-9]{11}$')),
  CONSTRAINT CK_USUARIO_EMAIL CHECK (REGEXP_LIKE(DS_EMAIL,'^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'))
);

CREATE TABLE USUARIO_PERFIL (
  ID_USUARIO  NUMBER NOT NULL,
  CD_PERFIL   VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT PK_USUARIO_PERFIL PRIMARY KEY (ID_USUARIO, CD_PERFIL),
  CONSTRAINT FK_USRPRF_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT CK_USRPRF_CD CHECK (CD_PERFIL IN
    ('BENEFICIARIO','PRESTADOR','FUSEX','LISURA','ADMIN'))
);

CREATE UNIQUE INDEX UX_USUARIO_EMAIL  ON USUARIO (LOWER(DS_EMAIL));
CREATE UNIQUE INDEX UX_PRESTADOR_NOME ON PRESTADOR (UPPER(TRIM(NM_PRESTADOR)));

CREATE INDEX IX_USUARIO_PRESTADOR ON USUARIO (ID_PRESTADOR);
CREATE INDEX IX_PREST_TIPO_ATIVO  ON PRESTADOR (TP_PRESTADOR, FL_ATIVO);
CREATE INDEX IX_USRPRF_PERFIL     ON USUARIO_PERFIL (CD_PERFIL);

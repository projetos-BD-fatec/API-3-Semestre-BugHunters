-- Revisão da Lisura: decisão do analista para cada item do espelho
-- (acatar o valor contratual, manter o cobrado ou informar um valor ajustado).

CREATE TABLE LISURA_REVISAO_ITEM (
    ID_REVISAO_ITEM       NUMBER GENERATED BY DEFAULT AS IDENTITY
                            CONSTRAINT PK_LISURA_REVISAO_ITEM PRIMARY KEY,
    ID_ESPELHO_ITEM       NUMBER NOT NULL
                            CONSTRAINT FK_LISREV_ESPITEM REFERENCES ESPELHO_ITEM (ID_ESPELHO_ITEM),
    DECISAO               VARCHAR2(20 CHAR) NOT NULL,
    VALOR_FINAL_UNITARIO  NUMBER(14,2) NOT NULL,
    ID_USUARIO            NUMBER NOT NULL
                            CONSTRAINT FK_LISREV_USUARIO REFERENCES USUARIO (ID_USUARIO),
    REVISADO_EM           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_LISREV_ESPITEM UNIQUE (ID_ESPELHO_ITEM),
    CONSTRAINT CK_LISREV_DECISAO CHECK (DECISAO IN ('ACATAR_CONTRATUAL','MANTER_COBRADO','VALOR_AJUSTADO')),
    CONSTRAINT CK_LISREV_VALOR   CHECK (VALOR_FINAL_UNITARIO >= 0)
);

CREATE INDEX IX_LISREV_USUARIO ON LISURA_REVISAO_ITEM (ID_USUARIO);

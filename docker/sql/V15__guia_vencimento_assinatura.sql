-- Vencimento da guia oficial + assinatura do beneficiario.
--
-- VENCIMENTO: DT_VALIDADE guarda ate que dia a guia pode ser utilizada.
--   O valor e calculado no upload (data do upload + N meses). O N fica em
--   backend/src/main/resources/application.properties: fusex.guia.validade-meses
--
-- ASSINATURA: o beneficiario "assina" a guia utilizada informando, via OCS,
--   um codigo de 6 digitos que so aparece no app dele. Os codigos ficam em
--   GUIA_ASSINATURA_CODIGO (curta duracao, uso unico, tentativas limitadas);
--   o resultado fica na propria guia (DT_ASSINATURA + ID_USUARIO_ASSINANTE).

ALTER TABLE GUIA_OFICIAL ADD (
    DT_VALIDADE           DATE,
    DT_ASSINATURA         TIMESTAMP(6),
    ID_USUARIO_ASSINANTE  NUMBER
);

ALTER TABLE GUIA_OFICIAL ADD CONSTRAINT FK_GUIA_USR_ASSINANTE
    FOREIGN KEY (ID_USUARIO_ASSINANTE) REFERENCES USUARIO (ID_USUARIO);

-- Guias que ja existiam: validade de 3 meses a partir do upload
-- (mesmo valor padrao de fusex.guia.validade-meses; ajuste aqui se mudar o prazo)
UPDATE GUIA_OFICIAL
   SET DT_VALIDADE = ADD_MONTHS(TRUNC(DATA_UPLOAD), 3)
 WHERE DT_VALIDADE IS NULL;

COMMIT;

-- Sera consultado pelo job que marca guias vencidas
CREATE INDEX IX_GUIA_STATUS_VALIDADE ON GUIA_OFICIAL (STATUS, DT_VALIDADE);

CREATE TABLE GUIA_ASSINATURA_CODIGO (
    ID_CODIGO        NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT PK_GUIA_ASSIN_CODIGO PRIMARY KEY,
    ID_GUIA_OFICIAL  NUMBER NOT NULL
                       CONSTRAINT FK_GUIA_ASSIN_GUIA REFERENCES GUIA_OFICIAL (ID_GUIA_OFICIAL),
    CODIGO           VARCHAR2(6 CHAR) NOT NULL,
    CRIADO_EM        TIMESTAMP(6) NOT NULL,
    EXPIRA_EM        TIMESTAMP(6) NOT NULL,
    TENTATIVAS       NUMBER(3) DEFAULT 0 NOT NULL,
    INVALIDADO_EM    TIMESTAMP(6),
    CONSTRAINT CK_GUIA_ASSIN_CODIGO CHECK (REGEXP_LIKE(CODIGO, '^[0-9]{6}$'))
);

CREATE INDEX IX_GUIA_ASSIN_GUIA ON GUIA_ASSINATURA_CODIGO (ID_GUIA_OFICIAL, INVALIDADO_EM);

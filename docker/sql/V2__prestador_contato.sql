CREATE TABLE PRESTADOR_CONTATO (
    ID_CONTATO   NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT PK_PRESTADOR_CONTATO PRIMARY KEY,
    ID_PRESTADOR NUMBER NOT NULL
                   CONSTRAINT FK_PREST_CONTATO_PRESTADOR REFERENCES PRESTADOR (ID_PRESTADOR),
    NM_CONTATO   VARCHAR2(150 CHAR),
    TP_CONTATO   VARCHAR2(30 CHAR) DEFAULT 'GERAL' NOT NULL,
    NR_TELEFONE  VARCHAR2(20 CHAR),
    DS_EMAIL     VARCHAR2(150 CHAR),
    FL_ATIVO     CHAR(1) DEFAULT 'S' NOT NULL,
    CRIADO_EM    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_PREST_CONTATO_TIPO CHECK (TP_CONTATO IN
        ('AGENDAMENTO','FATURAMENTO','RESPONSAVEL','GERAL')),
    CONSTRAINT CK_PREST_CONTATO_ATIVO CHECK (FL_ATIVO IN ('S','N')),
    CONSTRAINT CK_PREST_CONTATO_DADO CHECK (NR_TELEFONE IS NOT NULL OR DS_EMAIL IS NOT NULL)
);

CREATE INDEX IX_PREST_CONTATO_PRESTADOR ON PRESTADOR_CONTATO (ID_PRESTADOR);

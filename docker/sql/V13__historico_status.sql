-- =====================================================================
-- V13 - US17 / SCRUM-65 - Acompanhamento do fluxo da guia
--
-- Da solicitacao a liquidacao, o processo passa por seis etapas que hoje
-- vivem em tabelas diferentes (PRE_GUIA, GUIA_OFICIAL, ESPELHO) e que so
-- guardam o status ATUAL: a mudanca sobrescreve a linha e nada fica
-- registrado. Este script cria a trilha dessas mudancas.
--
-- Conteudo:
--   1) Garantia da CK_GUIA_OFICIAL_STATUS (ver nota abaixo)
--   2) Etapa de liquidacao na GUIA_OFICIAL
--   3) Tabela HISTORICO_STATUS + indices
--   4) Carga inicial do historico a partir das datas que ja existem
-- =====================================================================

SET SERVEROUTPUT ON

-- ---------------------------------------------------------------------
-- 1) Garantia da constraint de status da guia
--
-- O V12__status_guia_lisura.sql (SCRUM-53) ja deixa a CHECK aceitando
-- LISURA_APROVADA e LISURA_RECUSADA. Porem esse V12 existe na branch
-- main e NAO existe na develop -- quem montou o banco a partir da
-- develop ainda tem a CHECK antiga, e ai LisuraService.decidir() falha
-- com ORA-02290 ao gravar a decisao.
--
-- Sem esses dois status a etapa LISURA nunca e alcancada e a timeline
-- da US17 nasce incompleta, entao este bloco garante a constraint nos
-- dois casos. E idempotente: se o V12 ja rodou, nada muda.
--
-- (A diferenca entre as branches e um problema de merge do time, nao
--  deste script. Vale alinhar antes de subir o PR.)
-- ---------------------------------------------------------------------

DECLARE
    v_ok NUMBER;
BEGIN
    -- A CHECK ja aceita os dois status da Lisura?
    SELECT COUNT(*) INTO v_ok
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'CK_GUIA_OFICIAL_STATUS'
       AND CONSTRAINT_TYPE = 'C'
       AND INSTR(SEARCH_CONDITION_VC, 'LISURA_APROVADA') > 0;

    IF v_ok = 0 THEN
        BEGIN
            EXECUTE IMMEDIATE
                'ALTER TABLE GUIA_OFICIAL DROP CONSTRAINT CK_GUIA_OFICIAL_STATUS';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -2443 THEN RAISE; END IF;  -- -2443: constraint nao existe
        END;

        EXECUTE IMMEDIATE
            'ALTER TABLE GUIA_OFICIAL ADD CONSTRAINT CK_GUIA_OFICIAL_STATUS '
            || 'CHECK (STATUS IN (''ATIVA'',''UTILIZADA'',''VENCIDA'',''CANCELADA'','
            || '''LISURA_APROVADA'',''LISURA_RECUSADA''))';

        DBMS_OUTPUT.PUT_LINE('CK_GUIA_OFICIAL_STATUS atualizada (banco vinha sem o V12).');
    ELSE
        DBMS_OUTPUT.PUT_LINE('CK_GUIA_OFICIAL_STATUS ja aceita os status da Lisura.');
    END IF;
END;
/


---------------------------------------------------------------------
-- 2) Etapa de liquidacao
--
-- A liquidacao e a ultima etapa do fluxo da US17 e nao existia em lugar
-- nenhum do sistema. Ela nao vira um novo valor de STATUS para nao
-- apagar o resultado da Lisura (uma guia liquidada continua sendo uma
-- guia LISURA_APROVADA); fica em colunas proprias.
--
-- Regra: as duas colunas andam juntas - ou as duas nulas (nao liquidada)
-- ou as duas preenchidas (quem liquidou e quando).
-- ---------------------------------------------------------------------

ALTER TABLE GUIA_OFICIAL ADD (
    LIQUIDADO_EM          TIMESTAMP(6),
    ID_USUARIO_LIQUIDACAO NUMBER
                            CONSTRAINT FK_GUIA_USUARIO_LIQUIDACAO
                            REFERENCES USUARIO (ID_USUARIO)
);

ALTER TABLE GUIA_OFICIAL ADD CONSTRAINT CK_GUIA_LIQUIDACAO
    CHECK ( (LIQUIDADO_EM IS     NULL AND ID_USUARIO_LIQUIDACAO IS     NULL)
         OR (LIQUIDADO_EM IS NOT NULL AND ID_USUARIO_LIQUIDACAO IS NOT NULL) );


-- ---------------------------------------------------------------------
-- 3) Trilha de mudancas de status
--
-- A linha do tempo e ancorada na PRE_GUIA, e nao na guia oficial,
-- porque a primeira etapa (solicitacao) acontece ANTES de a guia
-- existir. ID_GUIA_OFICIAL so e preenchido da emissao em diante.
--
-- STATUS_ANTERIOR nulo = primeiro registro daquela etapa.
-- ID_USUARIO nulo = mudanca sem usuario identificado (carga inicial).
-- ---------------------------------------------------------------------

CREATE TABLE HISTORICO_STATUS (
    ID_HISTORICO    NUMBER GENERATED BY DEFAULT AS IDENTITY
                      CONSTRAINT PK_HISTORICO_STATUS PRIMARY KEY,
    ID_PRE_GUIA     NUMBER NOT NULL
                      CONSTRAINT FK_HIST_PRE_GUIA
                      REFERENCES PRE_GUIA (ID_PRE_GUIA),
    ID_GUIA_OFICIAL NUMBER
                      CONSTRAINT FK_HIST_GUIA
                      REFERENCES GUIA_OFICIAL (ID_GUIA_OFICIAL),
    ETAPA           VARCHAR2(20 CHAR) NOT NULL,
    STATUS_ANTERIOR VARCHAR2(20 CHAR),
    STATUS_NOVO     VARCHAR2(20 CHAR) NOT NULL,
    ID_USUARIO      NUMBER
                      CONSTRAINT FK_HIST_USUARIO
                      REFERENCES USUARIO (ID_USUARIO),
    OBSERVACAO      VARCHAR2(400 CHAR),
    REGISTRADO_EM   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_HIST_ETAPA CHECK (ETAPA IN ('SOLICITACAO',
                                              'EMISSAO',
                                              'REALIZACAO',
                                              'FATURAMENTO',
                                              'LISURA',
                                              'LIQUIDACAO'))
);

COMMENT ON TABLE  HISTORICO_STATUS                 IS 'US17: trilha das mudancas de status de cada etapa do fluxo, da solicitacao a liquidacao.';
COMMENT ON COLUMN HISTORICO_STATUS.ID_PRE_GUIA     IS 'Processo a que o evento pertence. Sempre preenchido: a solicitacao e a raiz do fluxo.';
COMMENT ON COLUMN HISTORICO_STATUS.ID_GUIA_OFICIAL IS 'Guia oficial, quando ja emitida. Nulo nos eventos anteriores a emissao.';
COMMENT ON COLUMN HISTORICO_STATUS.ETAPA           IS 'Etapa do fluxo da US17.';
COMMENT ON COLUMN HISTORICO_STATUS.STATUS_ANTERIOR IS 'Status de onde saiu. Nulo no primeiro registro da etapa.';
COMMENT ON COLUMN HISTORICO_STATUS.ID_USUARIO      IS 'Quem fez a mudanca. Nulo na carga inicial.';

-- Consulta principal: trilha de um processo em ordem cronologica.
CREATE INDEX IX_HIST_PRE_GUIA ON HISTORICO_STATUS (ID_PRE_GUIA, REGISTRADO_EM);

-- Consulta pela guia (tela de acompanhamento abre pelo ID da guia).
CREATE INDEX IX_HIST_GUIA ON HISTORICO_STATUS (ID_GUIA_OFICIAL);


-- ---------------------------------------------------------------------
-- 4) Carga inicial
--
-- Sem isso toda guia que ja existe apareceria com a linha do tempo
-- vazia, porque a trilha so passa a ser gravada daqui para a frente.
-- As datas abaixo sao as que o banco ja guarda.
--
-- ATENCAO: duas etapas nao tem data propria no modelo atual e sao
-- ESTIMADAS (a observacao de cada linha diz isso). Eventos novos,
-- gravados pela aplicacao, tem a data real.
-- ---------------------------------------------------------------------

-- SOLICITACAO: data de criacao da pre-guia (exata).
INSERT INTO HISTORICO_STATUS
    (ID_PRE_GUIA, ID_GUIA_OFICIAL, ETAPA, STATUS_ANTERIOR, STATUS_NOVO,
     ID_USUARIO, OBSERVACAO, REGISTRADO_EM)
SELECT pg.ID_PRE_GUIA,
       NULL,
       'SOLICITACAO',
       NULL,
       'EM_ANALISE',
       pg.ID_USUARIO,
       'Carga inicial US17: data de criacao da pre-guia.',
       pg.CRIADO_EM
  FROM PRE_GUIA pg;

-- EMISSAO: data de upload da guia oficial (exata).
INSERT INTO HISTORICO_STATUS
    (ID_PRE_GUIA, ID_GUIA_OFICIAL, ETAPA, STATUS_ANTERIOR, STATUS_NOVO,
     ID_USUARIO, OBSERVACAO, REGISTRADO_EM)
SELECT g.SOLICITACAO_ID,
       g.ID_GUIA_OFICIAL,
       'EMISSAO',
       'EM_ANALISE',
       'ATIVA',
       NULL,
       'Carga inicial US17: data de upload da guia oficial.',
       g.DATA_UPLOAD
  FROM GUIA_OFICIAL g;

-- REALIZACAO: a utilizacao da guia nunca foi datada. O espelho so e
-- aberto depois que a guia vira UTILIZADA, entao a abertura do espelho
-- e o limite superior mais proximo que o banco tem. Data ESTIMADA.
INSERT INTO HISTORICO_STATUS
    (ID_PRE_GUIA, ID_GUIA_OFICIAL, ETAPA, STATUS_ANTERIOR, STATUS_NOVO,
     ID_USUARIO, OBSERVACAO, REGISTRADO_EM)
SELECT g.SOLICITACAO_ID,
       g.ID_GUIA_OFICIAL,
       'REALIZACAO',
       'ATIVA',
       'UTILIZADA',
       NULL,
       'Carga inicial US17: data ESTIMADA pela abertura do espelho - a utilizacao nao era registrada.',
       e.CRIADO_EM
  FROM GUIA_OFICIAL g
  JOIN ESPELHO e
    ON e.ID_GUIA_OFICIAL = g.ID_GUIA_OFICIAL
 WHERE g.STATUS IN ('UTILIZADA', 'LISURA_APROVADA', 'LISURA_RECUSADA');

-- FATURAMENTO: data de envio do espelho (exata).
INSERT INTO HISTORICO_STATUS
    (ID_PRE_GUIA, ID_GUIA_OFICIAL, ETAPA, STATUS_ANTERIOR, STATUS_NOVO,
     ID_USUARIO, OBSERVACAO, REGISTRADO_EM)
SELECT g.SOLICITACAO_ID,
       g.ID_GUIA_OFICIAL,
       'FATURAMENTO',
       'RASCUNHO',
       'ENVIADO',
       NULL,
       'Carga inicial US17: data de envio do espelho.',
       e.ENVIADO_EM
  FROM GUIA_OFICIAL g
  JOIN ESPELHO e
    ON e.ID_GUIA_OFICIAL = g.ID_GUIA_OFICIAL
 WHERE e.STATUS = 'ENVIADO'
   AND e.ENVIADO_EM IS NOT NULL;

-- LISURA: a decisao nao tem data propria. Usa a ultima revisao de item
-- do espelho e, quando nao houver revisao (recusa direta), o envio do
-- espelho. Data ESTIMADA.
INSERT INTO HISTORICO_STATUS
    (ID_PRE_GUIA, ID_GUIA_OFICIAL, ETAPA, STATUS_ANTERIOR, STATUS_NOVO,
     ID_USUARIO, OBSERVACAO, REGISTRADO_EM)
SELECT g.SOLICITACAO_ID,
       g.ID_GUIA_OFICIAL,
       'LISURA',
       'UTILIZADA',
       g.STATUS,
       NULL,
       'Carga inicial US17: data ESTIMADA pela ultima revisao de item.',
       NVL( (SELECT MAX(r.REVISADO_EM)
               FROM LISURA_REVISAO_ITEM r
               JOIN ESPELHO_ITEM ei
                 ON ei.ID_ESPELHO_ITEM = r.ID_ESPELHO_ITEM
              WHERE ei.ID_ESPELHO = e.ID_ESPELHO),
            e.ENVIADO_EM )
  FROM GUIA_OFICIAL g
  JOIN ESPELHO e
    ON e.ID_GUIA_OFICIAL = g.ID_GUIA_OFICIAL
 WHERE g.STATUS IN ('LISURA_APROVADA', 'LISURA_RECUSADA');

-- LIQUIDACAO: etapa criada agora, nao ha nada para carregar.

COMMIT;

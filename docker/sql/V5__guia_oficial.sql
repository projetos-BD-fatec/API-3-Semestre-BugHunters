CREATE TABLE GUIA_OFICIAL (
    ID_GUIA_OFICIAL  NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT PK_GUIA_OFICIAL PRIMARY KEY,
    SOLICITACAO_ID   NUMBER NOT NULL
                       CONSTRAINT FK_GUIA_PRE_GUIA REFERENCES PRE_GUIA (ID_PRE_GUIA),
    CODIGO_GUIA      VARCHAR2(50 CHAR),
    NOME_ARQUIVO     VARCHAR2(255 CHAR) NOT NULL,
    CAMINHO_ARQUIVO  VARCHAR2(500 CHAR) NOT NULL,
    DATA_UPLOAD      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS           VARCHAR2(20 CHAR) DEFAULT 'ATIVA' NOT NULL,
    CONSTRAINT UK_GUIA_OFICIAL_CODIGO UNIQUE (CODIGO_GUIA),
    CONSTRAINT CK_GUIA_OFICIAL_STATUS CHECK (STATUS IN ('ATIVA','UTILIZADA','VENCIDA','CANCELADA'))
);

CREATE INDEX IX_GUIA_OFICIAL_SOLIC ON GUIA_OFICIAL (SOLICITACAO_ID);

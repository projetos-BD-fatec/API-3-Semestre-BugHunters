CREATE TABLE PRE_GUIA_ITEM (
    ID_PRE_GUIA_ITEM NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_PRE_GUIA_ITEM_ID PRIMARY KEY,
    ID_PRE_GUIA NUMBER NOT NULL
        CONSTRAINT FK_PRE_GUIA_ID REFERENCES PRE_GUIA (ID_PRE_GUIA),
    ID_EXAME NUMBER NOT NULL
        CONSTRAINT FK_EXAME_ID REFERENCES EXAME (ID_EXAME),
    ID_PRESTADOR NUMBER NOT NULL
        CONSTRAINT FK_PRESTADOR_ID REFERENCES PRESTADOR (ID_PRESTADOR),
    VALOR NUMBER(10,2) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'EM_ANALISE' NOT NULL,
    CONSTRAINT UK_PRE_GUIA_EXAME UNIQUE (ID_PRE_GUIA, ID_EXAME)
);

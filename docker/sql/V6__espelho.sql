CREATE TABLE ESPELHO (
    ID_ESPELHO       NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT PK_ESPELHO PRIMARY KEY,
    ID_GUIA_OFICIAL  NUMBER NOT NULL
                       CONSTRAINT FK_ESPELHO_GUIA REFERENCES GUIA_OFICIAL (ID_GUIA_OFICIAL),
    ID_PRESTADOR     NUMBER NOT NULL
                       CONSTRAINT FK_ESPELHO_PRESTADOR REFERENCES PRESTADOR (ID_PRESTADOR),
    STATUS           VARCHAR2(20 CHAR) DEFAULT 'RASCUNHO' NOT NULL,
    CRIADO_EM        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM    TIMESTAMP(6),
    ENVIADO_EM       TIMESTAMP(6),
    CONSTRAINT UK_ESPELHO_GUIA UNIQUE (ID_GUIA_OFICIAL),
    CONSTRAINT CK_ESPELHO_STATUS CHECK (STATUS IN ('RASCUNHO','ENVIADO'))
);

CREATE TABLE ESPELHO_ITEM (
    ID_ESPELHO_ITEM  NUMBER GENERATED BY DEFAULT AS IDENTITY
                       CONSTRAINT PK_ESPELHO_ITEM PRIMARY KEY,
    ID_ESPELHO       NUMBER NOT NULL
                       CONSTRAINT FK_ESPITEM_ESPELHO REFERENCES ESPELHO (ID_ESPELHO),
    COD_TUSS         VARCHAR2(200 CHAR) NOT NULL
                       CONSTRAINT FK_ESPITEM_TUSS REFERENCES CATALOGO_TUSS (COD_TUSS),
    DT_REALIZACAO    DATE NOT NULL,
    QUANTIDADE       NUMBER(6) NOT NULL,
    VALOR_UNITARIO   NUMBER(14,2) NOT NULL,
    CONSTRAINT CK_ESPITEM_QTD   CHECK (QUANTIDADE > 0),
    CONSTRAINT CK_ESPITEM_VALOR CHECK (VALOR_UNITARIO >= 0)
);

CREATE INDEX IX_ESPITEM_ESPELHO ON ESPELHO_ITEM (ID_ESPELHO);
